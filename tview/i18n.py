def set_language(lang: str | None) -> None:
    """设置全局语言（zh/en），未知值回退中文。"""
    global _lang
    _lang = lang if lang in _STRINGS else "zh"


def tr(key: str) -> str:
    """取当前语言的字符串；缺 key 回退中文，再缺返回 key 本身。"""
    return _STRINGS[_lang].get(key) or _STRINGS["zh"].get(key, key)


def languages() -> list[str]:
    return list(_STRINGS.keys())


_WEEKDAYS_EN = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"]
_MONTHS_EN = ["Jan", "Feb", "Mar", "Apr", "May", "Jun",
              "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]


def format_date(dt) -> str:
    """按当前语言格式化日期（中文: 2026年8月9日 星期日 / 英文: Sun, Aug 9, 2026）。
    英文不用 strftime(%a/%b)——系统 zh_CN locale 会输出中文缩写，必须自拼。"""
    if _lang == "zh":
        return f"{dt.year}年{dt.month}月{dt.day}日 星期{'一二三四五六日'[dt.weekday()]}"
    return f"{_WEEKDAYS_EN[dt.weekday()]}, {_MONTHS_EN[dt.month - 1]} {dt.day}, {dt.year}"
